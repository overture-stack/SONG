/**
 * Writes {@link ReleaseDatabase#DUMP_PATH}: a dump of a database migrated and populated by the
 * current code. Run it once on the release before an upgrade, with {@code
 * -Drelease.dump.generate=true}; {@link ReleaseDumpUpgradeTest} then starts newer code against it.
 *
 * <p>The database holds the seed data, a study with a published analysis created from the contract
 * payload, and a second version of the variantCall analysis type.
 */
@SpringBootTest
@ExtendWith(SpringExtension.class)
@ActiveProfiles("test")
@EnabledIfSystemProperty(named = "release.dump.generate", matches = "true")
public class ReleaseDumpGenerator {

  public static final String DUMP_STUDY_ID = "DUMP-STUDY";

  /** Started when the context is built, so a disabled run starts no container. */
  private static PostgreSQLContainer<?> postgres;

  @DynamicPropertySource
  static void registerDatasource(DynamicPropertyRegistry registry) {
    postgres = ReleaseDatabase.startContainer();
    ReleaseDatabase.registerDatasource(registry, postgres);
  }

  @AfterAll
  public static void stopDatabase() {
    if (postgres != null) {
      postgres.stop();
    }
  }

  @Autowired private StudyService studyService;
  @Autowired private AnalysisService analysisService;
  @Autowired private AnalysisTypeService analysisTypeService;
  @Autowired private AnalysisRepository analysisRepository;

  @Test
  @SneakyThrows
  public void generateDump() {
    studyService.saveStudy(
        Study.builder()
            .studyId(DUMP_STUDY_ID)
            .name("Dump study")
            .organization("Upgrade test")
            .description("Created by ReleaseDumpGenerator")
            .build());

    val payload =
        (ObjectNode)
            ResourceFetcher.builder()
                .resourceType(ResourceFetcher.ResourceType.TEST)
                .dataDir(Paths.get("documents/contract"))
                .build()
                .readJsonNode("variantcall-payload.json");
    payload.put("studyId", DUMP_STUDY_ID);
    val analysisId =
        analysisService.create(DUMP_STUDY_ID, fromJson(payload, Payload.class)).getAnalysisId();
    val analysis = analysisRepository.findById(analysisId).get();
    analysis.setAnalysisState(PUBLISHED.name());
    analysisRepository.save(analysis);

    val schema = new ObjectMapper().createObjectNode();
    schema.put("type", "object");
    schema.putObject("properties").putObject("note").put("type", "string");
    analysisTypeService.register("variantCall", new AnalysisTypeOptions(), schema);

    Files.createDirectories(ReleaseDatabase.DUMP_PATH.getParent());
    Files.writeString(
        ReleaseDatabase.DUMP_PATH,
        "-- Generated by ReleaseDumpGenerator from the release before the upgrade.\n"
            + ReleaseDatabase.dump(postgres),
        StandardCharsets.UTF_8);
  }
}
